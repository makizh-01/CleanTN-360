export const TN_ZONES = ['Northern', 'Western', 'Central', 'Southern'];

export function getDistrictByCode(code) {
  if (!code) return null;
  const c = code.toUpperCase();
  return TN_DISTRICTS_DIRECTORY.find(d => d.code === c || d.name.toUpperCase() === c) || null;
}

export function getDistrictByName(name) {
  if (!name) return null;
  const n = name.trim().toLowerCase();
  return TN_DISTRICTS_DIRECTORY.find(d => d.name.toLowerCase() === n) || null;
}
